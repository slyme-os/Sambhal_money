// `npm run seed` — writes supabase/seed.sql from the same deterministic generator
// the browser demo uses: one operator, 25 pilot + 25 control riders, 30 days.
// Every row is marked entry_method = 'seed' (or lives under a seeded rider), so
// `npm run seed -- --purge` emits the SQL that removes it all before real riders.
//
// Load it with the Supabase CLI (`supabase db reset` runs seed.sql automatically)
// or `psql "$DATABASE_URL" -f supabase/seed.sql`.

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { generateFleet, type Fleet } from "../lib/seed";
import { seedUuid } from "../lib/ids";
import type { PotKind } from "../lib/types";

const POT_LABELS: Record<PotKind, [string, string]> = {
  rent: ["किराया", "Rent"],
  emergency: ["इमरजेंसी", "Emergency"],
  savings: ["बचत", "Savings"],
};

function lit(value: string | number | boolean | null | undefined): string {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number") return String(value);
  if (typeof value === "boolean") return value ? "true" : "false";
  return `'${value.replace(/'/g, "''")}'`;
}

function insert(table: string, columns: string[], rows: (string | number | boolean | null)[][]): string {
  if (rows.length === 0) return "";
  const values = rows.map((r) => `  (${r.map(lit).join(", ")})`).join(",\n");
  return `insert into public.${table} (${columns.join(", ")}) values\n${values};\n`;
}

export function potId(riderId: string, kind: PotKind): string {
  return seedUuid(`${riderId}:pot:${kind}`);
}

export function buildSeedSql(fleet: Fleet): string {
  const op = fleet.operator;
  const out: string[] = [
    "-- Generated by `npm run seed`. FAKE DATA — every rider and row here is seeded.",
    "-- Purge before real riders: npm run seed -- --purge",
    "begin;",
    insert("operators", ["id", "name", "city", "contact_name", "contact_phone", "code", "payee_vpa"], [
      [op.id, op.name, op.city, op.contactName, op.contactPhone, op.code, op.payeeVpa],
    ]),
  ];

  for (const b of fleet.riders) {
    const r = b.rider;
    out.push(
      insert(
        "riders",
        ["id", "name", "phone", "operator_id", "city", "language", "floor_paise", "cohort", "entry_method", "onboarded_at", "created_at"],
        [[r.id, r.name, r.phone, r.operatorId, r.city, r.language, r.floorPaise, r.cohort, "seed", r.onboardedAt, r.createdAt]],
      ),
      insert(
        "consents",
        ["id", "rider_id", "purpose", "granted", "version", "granted_at", "withdrawn_at"],
        b.consents.map((c) => [c.id, c.riderId, c.purpose, c.granted, c.version, c.grantedAt, c.withdrawnAt]),
      ),
      insert(
        "pots",
        ["id", "rider_id", "kind", "label_hi", "label_en", "target_paise"],
        (["rent", "emergency", "savings"] as const).map((k) => [
          potId(r.id, k), r.id, k, POT_LABELS[k][0], POT_LABELS[k][1],
          k === "rent" ? b.rentAgreement.amountPaise : k === "emergency" ? r.split.emergencyTargetPaise : null,
        ]),
      ),
      insert(
        "payouts",
        ["id", "rider_id", "amount_paise", "source", "occurred_at", "entry_method", "created_at"],
        b.payouts.map((p) => [p.id, p.riderId, p.amountPaise, p.source, p.occurredAt, p.entryMethod, p.createdAt]),
      ),
      insert(
        "spends",
        ["id", "rider_id", "amount_paise", "occurred_at", "entry_method", "created_at"],
        b.spends.map((s) => [s.id, s.riderId, s.amountPaise, s.occurredAt, s.entryMethod, s.createdAt]),
      ),
      // Allocations before withdrawals so the balance never dips below zero mid-load.
      insert(
        "allocations",
        ["id", "payout_id", "pot_id", "amount_paise", "created_at"],
        b.allocations.map((a) => [a.id, a.payoutId, potId(r.id, a.potKind), a.amountPaise, a.createdAt]),
      ),
      insert(
        "withdrawals",
        ["id", "pot_id", "amount_paise", "reason", "status", "requested_at", "settled_at"],
        b.withdrawals.map((w) => [w.id, potId(r.id, w.potKind), w.amountPaise, w.reason, w.status, w.requestedAt, w.settledAt]),
      ),
      insert(
        "rent_agreements",
        ["id", "rider_id", "operator_id", "amount_paise", "cadence", "due_weekday", "next_due_on", "payee_vpa", "payee_name", "active"],
        [[
          b.rentAgreement.id, r.id, b.rentAgreement.operatorId, b.rentAgreement.amountPaise, b.rentAgreement.cadence,
          b.rentAgreement.dueWeekday, b.rentAgreement.nextDueOn, b.rentAgreement.payeeVpa, b.rentAgreement.payeeName, b.rentAgreement.active,
        ]],
      ),
      insert(
        "rent_events",
        ["id", "rent_agreement_id", "due_on", "amount_paise", "status", "paid_at", "method", "rider_report", "rider_reported_at", "operator_report", "operator_reported_at"],
        b.rentEvents.map((e) => [
          e.id, e.rentAgreementId, e.dueOn, e.amountPaise, e.status, e.paidAt, e.method,
          e.riderReport, e.riderReportedAt, e.operatorReport, e.operatorReportedAt,
        ]),
      ),
      insert(
        "nudges",
        ["id", "rider_id", "kind", "sent_at", "acted_at", "dismissed_at", "context_json"],
        b.nudges.map((n) => [n.id, n.riderId, n.kind, n.sentAt, n.actedAt, n.dismissedAt, JSON.stringify(n.context)]),
      ),
      insert(
        "shock_events",
        ["id", "rider_id", "description", "amount_paise", "covered_by", "occurred_at"],
        b.shocks.map((s) => [s.id, s.riderId, s.description, s.amountPaise, s.coveredBy, s.occurredAt]),
      ),
    );
  }
  out.push("commit;");
  return out.filter(Boolean).join("\n");
}

/** Removes every seeded rider (cascades to all their rows) and the demo operator. */
export function buildPurgeSql(fleet: Fleet): string {
  return [
    "begin;",
    "delete from public.riders where entry_method = 'seed';",
    `delete from public.operators where id = ${lit(fleet.operator.id)} and not exists (select 1 from public.riders where operator_id = ${lit(fleet.operator.id)});`,
    "commit;",
    "",
  ].join("\n");
}

function main() {
  const purge = process.argv.includes("--purge");
  const fleet = generateFleet({ now: new Date().toISOString() });
  const file = join(process.cwd(), "supabase", purge ? "purge-seed.sql" : "seed.sql");
  writeFileSync(file, purge ? buildPurgeSql(fleet) : buildSeedSql(fleet));
  const rows = fleet.riders.reduce((s, b) => s + b.payouts.length + b.allocations.length + b.rentEvents.length, 0);
  console.log(`${purge ? "Purge" : "Seed"} SQL written to ${file} (${fleet.riders.length} riders, ~${rows} ledger rows)`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
